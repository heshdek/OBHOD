  BASE_H: 540,          // минимальная видимая высота мира

  GRAVITY: 2800,
  JUMP_V: 900,          // скорость отрыва: обычный прыжок ≈ 145
  HOLD_FROM: 0.08,      // удержание после этого времени — высокий прыжок
  HOLD_TO: 0.40,
  HOLD_GRAV: 0.32,      // доля гравитации при удержании (высокий прыжок ≈ 250)
  FAST_FALL_V: 1500,    // свайп вниз в воздухе — быстро на землю
  JUMP_BUFFER: 0.14,

  SPEED_START: 340,
  SPEED_MAX: 860,
  SPEED_ACCEL: 6,       // прирост скорости в секунду
  UNITS_PER_M: 40,

  STAMINA_DRAIN: 2.6,   // в секунду (100 → 0 примерно за 38 с)
  WATER_ADD: 38,
  MELON_ADD: 10,

  LIVES: 3,
